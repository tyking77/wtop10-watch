// Builds schedule.js from the Cablecast X-List CSVs in schedule/.
//
//   node scripts/build-schedule.mjs
//
// Drop a new export into schedule/ (on GitHub: Add file > Upload files) and
// the Action runs this. Exports overlap, so for any day covered by more than
// one file, the newest file wins that whole day. Days before yesterday
// are dropped. The output is the merged CSV as a string, loaded by a
// <script> tag so the pages still work from file://. guide-core.js parses it
// in the browser; this script parses it too, only to print the report.

import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";
import { createRequire } from "node:module";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIR = join(ROOT, "schedule");
const OUT = join(ROOT, "schedule.js");
const KEEP_DAYS_BACK = 1;
const core = createRequire(import.meta.url)(join(ROOT, "guide-core.js"));

// When a file arrived: its last commit time, or its modified time if it
// hasn't been committed yet (a local run)
function arrived(file) {
  const r = spawnSync("git", ["log", "-1", "--format=%ct", "--", file], { cwd: ROOT, encoding: "utf8" });
  const t = parseInt((r.stdout || "").trim(), 10);
  return t > 0 ? t * 1000 : statSync(file).mtimeMs;
}

function csvField(v) {
  v = String(v == null ? "" : v);
  return /[",\n]/.test(v) ? '"' + v.replace(/"/g, '""') + '"' : v;
}

const files = existsSync(DIR)
  ? readdirSync(DIR).filter((f) => /\.csv$/i.test(f)).map((f) => join(DIR, f))
  : [];
if (!files.length) {
  console.log("No CSVs in schedule/. Leaving schedule.js as it is.");
  process.exit(0);
}

// Newest first
const sources = files.map((file) => ({ file, time: arrived(file) })).sort((a, b) => b.time - a.time);

let header = null;
const byDay = new Map(); // "2026-09-18" -> { from, rows }
for (const src of sources) {
  const rows = core.parseCsvRows(readFileSync(src.file, "utf8"));
  if (!rows.length) continue;
  const cols = rows[0].map((h) => String(h || "").trim());
  const iDate = cols.indexOf("Program Start Date");
  if (iDate < 0) { console.warn(`! ${src.file}: no "Program Start Date" column, skipped`); continue; }
  if (!header) header = rows[0];
  const want = header.map((h) => cols.indexOf(String(h || "").trim()));
  const days = new Map();
  for (const row of rows.slice(1)) {
    const d = core.parseLooseDate(row[iDate]);
    const iso = d ? core.isoDate(d.y, d.m, d.d) : "undated";
    if (!days.has(iso)) days.set(iso, []);
    days.get(iso).push(want.map((i) => (i < 0 ? "" : row[i])));
  }
  for (const [iso, list] of days) {
    if (!byDay.has(iso)) byDay.set(iso, { from: src.file, rows: list }); // newer file already won
  }
}

const today = core.todayIso();
const p = core.isoToParts(today);
const cutoff = core.isoOfKey(core.absMinToKey(core.keyToAbsMin(core.keyOf(p.y, p.m, p.d, 0, 0)) - KEEP_DAYS_BACK * 1440));
const days = [...byDay.keys()].filter((iso) => iso === "undated" || iso >= cutoff).sort();

const lines = [header.map(csvField).join(",")];
for (const iso of days) for (const row of byDay.get(iso).rows) lines.push(row.map(csvField).join(","));
const csv = lines.join("\n") + "\n";

const res = core.parseStationCsv(csv);
const r = res.report;
if (r.fatal) { console.error("Schedule not built: " + r.fatal); process.exit(1); }

const used = [...new Set(days.map((d) => byDay.get(d).from))].map((f) => f.slice(DIR.length + 1));
writeFileSync(OUT,
  "/* Generated by scripts/build-schedule.mjs from " + used.join(", ") + ".\n" +
  "   Do not edit: upload a new Cablecast CSV to schedule/ instead. */\n" +
  "window.WTOP_SCHEDULE_CSV = " + JSON.stringify(csv) + ";\n");

console.log(`Wrote schedule.js: ${days.filter((d) => d !== "undated").join(", ")}`);
console.log(`  ${r.parsed} of ${r.dataRows} rows parsed, ${r.skipped.length} skipped`);
// One line per kind of skip ("Off Air" rows have no end time, for example)
const skips = new Map();
for (const s of r.skipped) {
  const k = (s.raw || "no title") + ": " + s.reason;
  skips.set(k, (skips.get(k) || 0) + 1);
}
for (const [k, n] of skips) console.log(`  ! skipped ${n > 1 ? n + " rows" : "1 row"}: ${k}`);
for (const m of r.durMismatch) console.log(`  ! duration mismatch: ${m.raw} says ${m.stated} min, times give ${m.computed}`);
if (r.uncategorized.length) console.log(`  ! no category rule, filed as ${core.DEFAULT_CAT}: ${r.uncategorized.join("; ")}`);
